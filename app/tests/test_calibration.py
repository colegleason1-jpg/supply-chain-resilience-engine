class TestOnlyEvidenceMakesANumberCalibrated:
    def stored_run(self, elasticity: float = 0.2):
        records, _ = adapters.build_delivery_records(history_frame(), NODE_IDS)
        run = calibrate_exposures(
            [exposure(elasticity=elasticity)], records, provider=provider_with_history()
        )
        return run

    def test_only_adoptable_fits_are_stored_as_evidence(self) -> None:
        """A refused fit is not evidence, and a row in the saved file would look like it.

        Anyone opening a saved portfolio and seeing a calibration row would reasonably
        conclude the number beside it was measured.
        """
        run = self.stored_run()
        assert run.calibrations[0].can_adopt

        thin, _ = adapters.build_delivery_records(
            history_frame(periods=list(PRICES)[:4]), NODE_IDS
        )
        refused = calibrate_exposures([exposure()], thin, provider=provider_with_history())

        assert refused.calibrations[0].fit.quality is FitQuality.TOO_FEW_OBSERVATIONS
        assert records_from_run(refused) == ()
        assert len(records_from_run(run)) == 1

    def test_a_stored_fit_records_the_method_that_produced_it(self) -> None:
        stored = records_from_run(self.stored_run())[0]

        assert stored.method == CALIBRATION_VERSION
        assert stored.observations == len(PRICES)

    def test_an_exposure_matching_its_stored_fit_reads_as_calibrated(self) -> None:
        stored = records_from_run(self.stored_run())[0]
        adopted = exposure(elasticity=stored.elasticity)

        resolved = adapters.resolve_elasticity_sources([adopted], [stored])

        assert resolved[0].is_calibrated
        assert CALIBRATION_VERSION in resolved[0].elasticity_source

    def test_overtyping_a_calibrated_elasticity_silently_reverts_it_to_asserted(self) -> None:
        """The whole reason provenance is derived rather than stored beside the number.

        A "source" column would still say calibrated after the edit. Here the label is
        recomputed from evidence every run, so a number a person changed is a number a
        person is asserting — and it is labelled that way without anyone remembering to.
        """
        stored = records_from_run(self.stored_run())[0]
        edited = exposure(elasticity=stored.elasticity + 0.15)

        resolved = adapters.resolve_elasticity_sources([edited], [stored])

        assert resolved[0].is_calibrated is False
        assert resolved[0].elasticity_source == adapters.ASSERTED

    def test_moving_the_anchor_also_revokes_the_calibrated_label(self) -> None:
        """The elasticity is defined relative to the anchor it was fitted against.

        A fit against deviations from 80 says nothing about deviations from 95, and
        keeping the label would carry the authority of a measurement over to a quantity
        nobody measured.
        """
        stored = records_from_run(self.stored_run())[0]
        moved = exposure(elasticity=stored.elasticity, anchor=95.0)

        resolved = adapters.resolve_elasticity_sources([moved], [stored])

        assert resolved[0].is_calibrated is False

    def test_a_csv_round_trip_does_not_revoke_the_label(self) -> None:
        """The tolerance exists for this and only this.

        Saving and reloading a portfolio must not downgrade a calibrated elasticity,
        or the label would decay to "asserted" for everyone who closes the tab.
        """
        stored = records_from_run(self.stored_run())[0]
        frame = pd.DataFrame(
            [
                {
                    adapters.COL_CAL_NODE_ID: stored.node_id,
                    adapters.COL_CAL_SYMBOL: stored.symbol,
                    adapters.COL_CAL_ELASTICITY: stored.elasticity,
                    adapters.COL_CAL_ANCHOR: stored.anchor,
                    adapters.COL_CAL_METHOD: stored.method,
                    adapters.COL_CAL_OBS: stored.observations,
                }
            ]
        )
        reparsed, rejections = adapters.build_calibration_records(
            adapters.align_calibration_frame(pd.read_csv(pd.io.common.StringIO(frame.to_csv(index=False))))
        )

        assert not rejections.items
        resolved = adapters.resolve_elasticity_sources(
            [exposure(elasticity=stored.elasticity)], reparsed
        )
        assert resolved[0].is_calibrated

    def test_a_stored_row_with_no_method_cannot_vouch_for_anything(self) -> None:
        """It fails towards asserted, which is the safe direction."""
        frame = pd.DataFrame(
            [
                {
                    adapters.COL_CAL_NODE_ID: "N1",
                    adapters.COL_CAL_SYMBOL: "BZ=F",
                    adapters.COL_CAL_ELASTICITY: 0.5,
                    adapters.COL_CAL_ANCHOR: ANCHOR,
                    adapters.COL_CAL_METHOD: "",
                }
            ]
        )

        records, rejections = adapters.build_calibration_records(frame)

        assert records == ()
        assert any("method" in item for item in rejections.items)
        resolved = adapters.resolve_elasticity_sources([exposure(elasticity=0.5)], records)
        assert resolved[0].is_calibrated is False

    def test_a_forged_calibration_row_cannot_bless_an_arbitrary_number(self) -> None:
        """Hand-editing the evidence table is possible; making it agree is the barrier.

        This is not a security control — a determined user can edit both columns. It is
        a control against the accidental version, where a stale calibration row from a
        previous fit keeps vouching for a number that has since been changed.
        """
        forged = adapters.CalibrationRecord(
            node_id="N1",
            symbol="BZ=F",
            elasticity=0.5,
            anchor=ANCHOR,
            interval_low=0.4,
            interval_high=0.6,
            r_squared=0.9,
            observations=12,
            periods_above_anchor=8,
            method="hand-typed",
        )

        assert adapters.resolve_elasticity_sources([exposure(elasticity=2.0)], [forged])[
            0
        ].is_calibrated is False
        assert adapters.resolve_elasticity_sources([exposure(elasticity=0.5)], [forged])[
            0
        ].is_calibrated is True
