class TestParsingWhatSomebodyPasted:
    def test_a_clean_sheet_parses_every_row(self) -> None:
        records, rejections = adapters.build_delivery_records(history_frame(), NODE_IDS)

        assert len(records) == len(PRICES)
        assert not rejections.items
        assert records[0].node_id == "N1"

    @pytest.mark.parametrize(
        "written,expected",
        [
            ("2026-07", "2026-07"),
            ("2026-7", "2026-07"),
            ("2026/07", "2026-07"),
            ("2026-07-14", "2026-07"),
            ("07/2026", "2026-07"),
            ("Jul 2026", "2026-07"),
            ("2026-07-31", "2026-07"),
        ],
    )
    def test_the_period_formats_people_actually_type_all_reduce_to_a_month(
        self, written, expected
    ) -> None:
        """Rejecting a date because it has a day in it teaches users to fight the tool."""
        assert adapters.normalise_period(written) == expected

    @pytest.mark.parametrize("written", ["", "Q3", "last summer", "2026-13", "13/2026", "-"])
    def test_a_period_that_cannot_be_read_is_refused_rather_than_guessed(
        self, written
    ) -> None:
        """The join is by month, so a guessed month is a silently wrong pairing.

        This is the failure with no symptom: the estimator would run happily on
        delivery performance matched to the wrong month's price and return a confident
        number about a relationship that was never in the data.
        """
        assert adapters.normalise_period(written) == ""

    def test_an_unreadable_period_is_reported_with_the_row_number(self) -> None:
        frame = history_frame()
        frame.loc[3, adapters.COL_HIST_PERIOD] = "third quarter"

        records, rejections = adapters.build_delivery_records(frame, NODE_IDS)

        assert len(records) == len(PRICES) - 1
        assert any("History row 4" in item for item in rejections.items)

    def test_two_rows_for_the_same_node_and_month_are_refused_not_averaged(self) -> None:
        """Averaging would produce a figure belonging to neither definition.

        A duplicate month is either a double paste or two teams measuring disruption
        differently. Both need a human; neither needs a mean.
        """
        frame = pd.concat([history_frame(), history_frame(periods=["2025-03"])])

        records, rejections = adapters.build_delivery_records(frame, NODE_IDS)

        assert len(records) == len(PRICES)
        assert any("duplicate" in item for item in rejections.items)

    def test_a_rate_above_one_hundred_percent_is_caught_as_a_unit_error(self) -> None:
        """The commonest paste error in this column, and it inflates every figure.

        A raw incident count in a percentage column would raise the fitted baseline and
        leave the elasticity plausible, so nothing downstream would look wrong.
        """
        frame = history_frame()
        frame.loc[2, adapters.COL_HIST_DISRUPTION] = 340.0

        records, rejections = adapters.build_delivery_records(frame, NODE_IDS)

        assert len(records) == len(PRICES) - 1
        assert any("not a count" in item for item in rejections.items)

    def test_a_row_naming_an_unknown_node_is_reported_and_the_rest_survive(self) -> None:
        frame = pd.concat([history_frame(), history_frame(node_id="GHOST", periods=["2025-05"])])

        records, rejections = adapters.build_delivery_records(frame, NODE_IDS)

        assert {r.node_id for r in records} == {"N1"}
        assert any("GHOST" in item for item in rejections.items)

    def test_a_wholly_blank_row_is_not_an_error(self) -> None:
        """The data editor adds one, so treating it as an error would mean the table is
        never valid while a user is typing in it."""
        frame = pd.concat(
            [history_frame(), pd.DataFrame([{c: None for c in adapters.HISTORY_COLUMNS}])]
        )

        records, rejections = adapters.build_delivery_records(frame, NODE_IDS)

        assert len(records) == len(PRICES)
        assert not rejections.items

    def test_renaming_a_node_does_not_delete_its_delivery_history(self) -> None:
        """Alignment keeps rows, unlike the exposure sheet's alignment.

        Delivery history is evidence of what happened. An intervention rename is an
        edit to a plan, and it must not destroy records — a user who renames back would
        otherwise find months of history gone with no undo.
        """
        aligned = adapters.align_history_frame(history_frame(node_id="OLD"))

        assert len(aligned) == len(PRICES)
        assert set(aligned[adapters.COL_HIST_NODE_ID]) == {"OLD"}


