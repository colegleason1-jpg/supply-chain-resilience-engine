"""Delivery history in, calibrated elasticity out — and the joins that go wrong.

The engine's tests cover the estimator. These cover the two things around it that
would break a correct estimator: parsing what a person pasted into a spreadsheet, and
joining their delivery months to a market's price months.
"""

from __future__ import annotations

import pandas as pd
import pytest

from scrcae.calibration import CALIBRATION_VERSION, FitQuality

from app import adapters
from app.services.calibration import calibrate_exposures, records_from_run
from app.services.feeds import PriceHistory, PricePoint, StaticProvider

NODE_IDS = ["N1", "N2"]
ANCHOR = 80.0

# A market that spends part of its life above the anchor of 80, which is the only
# reason an elasticity is estimable at all.
PRICES = {
    "2025-01": 70.0,
    "2025-02": 76.0,
    "2025-03": 84.0,
    "2025-04": 88.0,
    "2025-05": 96.0,
    "2025-06": 104.0,
    "2025-07": 92.0,
    "2025-08": 78.0,
    "2025-09": 100.0,
    "2025-10": 86.0,
    "2025-11": 108.0,
    "2025-12": 82.0,
}

TRUE_ELASTICITY = 0.5
BASELINE_PCT = 4.0


def disruption_for(period: str) -> float:
    """Disruption generated by the model, so the recoverable answer is known."""
    deviation = max((PRICES[period] - ANCHOR) / ANCHOR, 0.0)
    return BASELINE_PCT * (1.0 + TRUE_ELASTICITY * deviation)


def history_frame(node_id: str = "N1", periods=None) -> pd.DataFrame:
    periods = list(periods or PRICES)
    return pd.DataFrame(
        [
            {
                adapters.COL_HIST_NODE_ID: node_id,
                adapters.COL_HIST_PERIOD: period,
                adapters.COL_HIST_DISRUPTION: disruption_for(period),
            }
            for period in periods
        ]
    )


def exposure(node_id: str = "N1", elasticity: float = 0.2, anchor: float = ANCHOR):
    return adapters.NodeExposure(
        node_id=node_id, symbol="BZ=F", anchor=anchor, elasticity=elasticity
    )


def provider_with_history(prices=None) -> StaticProvider:
    return StaticProvider(
        prices={"BZ=F": 92.0},
        histories={"BZ=F": tuple((p, v) for p, v in (prices or PRICES).items())},
    )


