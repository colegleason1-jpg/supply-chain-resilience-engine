class TestCalibratingAnExposure:
    def test_a_clean_history_recovers_the_elasticity_that_generated_it(self) -> None:
        records, _ = adapters.build_delivery_records(history_frame(), NODE_IDS)

        run = calibrate_exposures([exposure()], records, provider=provider_with_history())

        assert len(run.calibrations) == 1
        fit = run.calibrations[0].fit
        assert fit is not None
        assert fit.elasticity == pytest.approx(TRUE_ELASTICITY, abs=1e-6)
        assert fit.baseline_disruption_rate == pytest.approx(BASELINE_PCT, abs=1e-6)

    def test_percentages_and_fractions_give_the_same_elasticity(self) -> None:
        """So a user who keeps disruption as 0.04 rather than 4.0 is not punished."""
        frame = history_frame()
        as_fraction = frame.copy()
        as_fraction[adapters.COL_HIST_DISRUPTION] = (
            as_fraction[adapters.COL_HIST_DISRUPTION] / 100.0
        )

        records_pct, _ = adapters.build_delivery_records(frame, NODE_IDS)
        records_frac, _ = adapters.build_delivery_records(as_fraction, NODE_IDS)

        pct = calibrate_exposures([exposure()], records_pct, provider=provider_with_history())
        frac = calibrate_exposures([exposure()], records_frac, provider=provider_with_history())

        assert pct.calibrations[0].fit.elasticity == pytest.approx(
            frac.calibrations[0].fit.elasticity, abs=1e-9
        )

    def test_a_delivery_month_with_no_market_price_is_dropped_by_name(self) -> None:
        """Never matched to the nearest month. That is the silent off-by-one.

        The dropped periods are listed so the user can see the gap in their own terms
        rather than wondering why the period count is lower than their row count.
        """
        records, _ = adapters.build_delivery_records(
            pd.concat([history_frame(), history_frame(periods=["2025-01"]).assign(**{
                adapters.COL_HIST_PERIOD: "2019-05"
            })]),
            NODE_IDS,
        )

        run = calibrate_exposures([exposure()], records, provider=provider_with_history())
        calibration = run.calibrations[0]

        assert "2019-05" in calibration.unmatched_periods
        assert calibration.matched_periods == len(PRICES)
        assert "2019-05" in calibration.headline()

    def test_two_nodes_on_the_same_market_are_fitted_against_one_series(self) -> None:
        """Otherwise their elasticities are not comparable.

        Two nodes exposed to copper must be measured against the same definition of the
        price of copper, or the multiplier on one is not on the same footing as the
        other and adding them tells you nothing.
        """
        frame = pd.concat([history_frame("N1"), history_frame("N2")])
        records, _ = adapters.build_delivery_records(frame, NODE_IDS)

        run = calibrate_exposures(
            [exposure("N1"), exposure("N2")], records, provider=provider_with_history()
        )

        assert set(run.histories) == {"BZ=F"}
        assert len(run.calibrations) == 2
        assert run.calibrations[0].fit.elasticity == pytest.approx(
            run.calibrations[1].fit.elasticity, abs=1e-9
        )

    def test_a_node_with_no_history_is_blocked_with_a_reason_not_a_zero(self) -> None:
        run = calibrate_exposures([exposure("N2")], (), provider=provider_with_history())
        calibration = run.calibrations[0]

        assert calibration.fit is None
        assert calibration.can_adopt is False
        assert "No delivery history recorded for N2" in calibration.blocked

    def test_a_market_with_no_history_is_blocked_and_names_the_feed_reason(self) -> None:
        """A spot-only feed must read as "cannot calibrate", not as "no relationship"."""
        records, _ = adapters.build_delivery_records(history_frame(), NODE_IDS)

        run = calibrate_exposures(
            [exposure()], records, provider=StaticProvider(prices={"BZ=F": 92.0})
        )
        calibration = run.calibrations[0]

        assert calibration.fit is None
        assert calibration.can_adopt is False
        assert "No price history for BZ=F" in calibration.blocked
        assert "No history supplied" in calibration.history_status

    def test_calibrating_with_no_exposures_configured_says_so_plainly(self) -> None:
        run = calibrate_exposures([], (), provider=provider_with_history())

        assert run.calibrations == ()
        assert "no market exposure has been configured" in run.summary()

    def test_a_supplied_history_needs_no_network_at_all(self) -> None:
        """The seam that makes this testable, asserted rather than assumed.

        The provider raises if touched. If a future refactor reintroduces a fetch on
        this path, this test fails rather than the suite quietly acquiring a network
        dependency.
        """

        class Exploding:
            name = "exploding"
            symbol_help = ""

            def latest(self, symbols, *, timeout=4.0):
                raise AssertionError("the feed was contacted")

            def history(self, symbol, *, months=60, timeout=8.0):
                raise AssertionError("the feed was contacted")

        records, _ = adapters.build_delivery_records(history_frame(), NODE_IDS)

        run = calibrate_exposures(
            [exposure()],
            records,
            provider=Exploding(),
            histories={
                "BZ=F": PriceHistory(
                    symbol="BZ=F",
                    points=tuple(PricePoint(p, v) for p, v in PRICES.items()),
                    status="Supplied",
                )
            },
        )

        assert run.calibrations[0].fit.elasticity == pytest.approx(TRUE_ELASTICITY, abs=1e-6)

    def test_the_delta_note_says_how_wrong_the_typed_number_was(self) -> None:
        """The usual point of a calibration is not the estimate, it is the gap."""
        records, _ = adapters.build_delivery_records(history_frame(), NODE_IDS)

        run = calibrate_exposures(
            [exposure(elasticity=0.1)], records, provider=provider_with_history()
        )

        note = run.calibrations[0].delta_note()
        assert "0.10" in note and "0.50" in note

    def test_an_entered_value_under_the_fit_is_called_below_it(self) -> None:
        """The direction word has to agree with the multiplier printed beside it.

        This test exists because the first version of the note printed entered/fitted
        (0.20) while labelling it with the direction of fitted/entered, so understating a
        risk elasticity was reported as being 'above the fit'. A wrong direction word here
        tells a reader their stale assumption is conservative when it is the opposite.
        """
        records, _ = adapters.build_delivery_records(history_frame(), NODE_IDS)

        run = calibrate_exposures(
            [exposure(elasticity=0.1)], records, provider=provider_with_history()
        )

        note = run.calibrations[0].delta_note()
        assert "0.20× the fit, below it" in note
        assert "above" not in note

    def test_an_entered_value_over_the_fit_is_called_above_it(self) -> None:
        """The other side of the same sentence."""
        records, _ = adapters.build_delivery_records(history_frame(), NODE_IDS)

        run = calibrate_exposures(
            [exposure(elasticity=1.0)], records, provider=provider_with_history()
        )

        note = run.calibrations[0].delta_note()
        assert "2.00× the fit, above it" in note
        assert "below" not in note


